// Real Electron + DPAPI, synthetic keys, isolated profile and runtime. No GitHub/model requests.
const { _electron, expect } = require('@playwright/test')
const { mkdtempSync, mkdirSync, readFileSync } = require('node:fs')
const { generateKeyPairSync } = require('node:crypto')
const path = require('node:path')
async function main() {
  const project = path.resolve(__dirname, '../..')
  const directory = path.join(project, '.local/desktop-tests'); mkdirSync(directory, { recursive: true })
  const fixture = mkdtempSync(path.join(directory, 'native-settings-'))
  const runtime = path.join(fixture, 'runtime'); const profile = path.join(fixture, 'profile'); const other = path.join(fixture, 'other-runtime')
  for (const dir of [runtime, profile, other]) mkdirSync(dir)
  const packaged = process.env.REPOPILOT_PACKAGED_EXE
  const env = { ...process.env, REPOPILOT_RUNTIME_DIR: runtime, REPOPILOT_DESKTOP_HOST_CONFIG: path.join(fixture, 'host.json'), REPOPILOT_DESKTOP_USER_DATA: profile, REPOPILOT_PYTHON: path.join(project, '.venv/Scripts/python.exe') }; delete env.ELECTRON_RUN_AS_NODE
  if (packaged) {
    env.PATH = path.join(process.env.SystemRoot || 'C:/Windows', 'System32')
    for (const name of ['REPOPILOT_PYTHON', 'PYTHONPATH', 'PYTHONHOME', 'VIRTUAL_ENV', 'CONDA_PREFIX']) delete env[name]
  }
  const launch = () => _electron.launch({ executablePath: packaged || require('electron'), args: packaged ? [] : [path.join(project, 'desktop')], cwd: packaged ? fixture : project, env })
  let app = await launch()
  try {
    let page = await app.firstWindow()
    await expect(page.getByRole('heading', { name: '还没有执行记录' })).toBeVisible({ timeout: 20000 })
    const noNode = await page.evaluate(() => typeof window.require === 'undefined')
    expect(noNode).toBe(true)
    const handle = page.getByRole('separator', { name: '调整导航栏宽度' })
    await handle.focus(); await page.keyboard.press('Shift+ArrowRight')
    await expect(page.locator('.sidebar')).toHaveCSS('width', '248px')
    await expect.poll(() => { try { return JSON.parse(readFileSync(env.REPOPILOT_DESKTOP_HOST_CONFIG)).panels.sidebarWidth } catch { return 0 } }).toBe(248)
    await page.getByRole('button', { name: '桌面设置与连接', exact: true }).click()
    await page.getByRole('button', { name: 'GitHub 机器人', exact: true }).click()
    await page.getByLabel('配置来源').selectOption('desktop')
    await page.getByLabel('App ID', { exact: true }).fill('1'); await page.getByLabel('Installation ID', { exact: true }).fill('2')
    await page.getByLabel('负责人 GitHub 用户名').fill('owner'); await page.getByLabel('连接检查仓库').fill('owner/repo')
    const { privateKey } = generateKeyPairSync('rsa', { modulusLength: 2048, privateKeyEncoding: { format: 'pem', type: 'pkcs8' }, publicKeyEncoding: { format: 'pem', type: 'spki' } })
    await page.locator('input[type=file]').setInputFiles({ name: 'synthetic.pem', mimeType: 'text/plain', buffer: Buffer.from(privateKey) })
    await page.getByRole('button', { name: '模型与预算', exact: true }).click(); await page.getByLabel('配置来源').selectOption('desktop')
    await page.getByLabel('模型 API Key', { exact: true }).fill('synthetic-native-model-key')
    await page.getByRole('button', { name: '保存设置', exact: true }).click()
    await expect(page.getByRole('status')).toContainText('配置已加密保存在本机')
    const blob = readFileSync(path.join(runtime, 'desktop-settings.bin'))
    expect(blob.includes(Buffer.from('synthetic-native-model-key'))).toBe(false); expect(blob.includes(Buffer.from('PRIVATE KEY'))).toBe(false)
    await page.getByRole('button', { name: '关闭', exact: true }).click()
    await page.evaluate(() => localStorage.clear())
    await app.close(); app = await launch(); page = await app.firstWindow()
    await expect(page.getByRole('heading', { name: '还没有执行记录' })).toBeVisible({ timeout: 20000 })
    await expect(page.locator('.sidebar')).toHaveCSS('width', '248px')
    await page.getByRole('button', { name: '桌面设置与连接', exact: true }).click()
    await page.getByRole('button', { name: 'GitHub 机器人', exact: true }).click()
    await expect(page.getByLabel('App ID', { exact: true })).toHaveValue('1')
    await expect(page.getByText('已配置私钥；原文不会回显。')).toBeVisible()
    await page.getByRole('button', { name: '模型与预算', exact: true }).click()
    await expect(page.getByLabel('模型 API Key', { exact: true })).toHaveValue('')
    await page.screenshot({ path: path.join(fixture, 'native-settings.png') })
    await page.getByRole('button', { name: '连接与本机', exact: true }).click()
    await app.evaluate(({ dialog }, directory) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [directory] }) }, other)
    await page.getByRole('button', { name: '选择其他运行目录' }).click()
    await expect.poll(() => page.evaluate(async () => (await window.repopilot.bootstrap()).runtime)).toBe(other)
    await expect(page.getByRole('heading', { name: '还没有执行记录' })).toBeVisible()
    await expect.poll(() => JSON.parse(readFileSync(env.REPOPILOT_DESKTOP_HOST_CONFIG)).runtime).toBe(other)
    console.log(JSON.stringify({ nativeSettings: 'passed', packaged: !!packaged, developmentRuntimeOnPath: !packaged, noNode, dpapi: true, restartPersistence: true, panePersistence: true, runtimeSwitch: true, githubWrites: 0, inferenceCalls: 0, evidence: fixture }))
  } finally { await app.close() }
}
main().catch(e => { console.error(e); process.exitCode = 1 })
